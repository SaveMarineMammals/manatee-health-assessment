/**
 * Verifies the linked platform checkout matches schema-pin.json, then generates
 * src/core/src/generated/pin.ts.
 *
 * The generated module is the single place the app learns which protocol version
 * it was built against. Records are stamped from it, and preflight displays it —
 * so the server can route validation by version instead of rejecting anything it
 * does not recognise. Nothing hardcodes a version string by hand.
 *
 * Commit drift is a warning locally (a working checkout moves around) but an
 * error in CI, where the pin is what was actually checked out.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const platformRoot = join(repoRoot, '.mmap-platform');
const schemaRoot = join(platformRoot, 'packages', 'schema');
const outDir = join(repoRoot, 'src', 'core', 'src', 'generated');
const outFile = join(outDir, 'pin.ts');

const isCi = process.env.CI === 'true' || process.env.CI === '1';

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function resolvedCommit() {
  try {
    return execFileSync('git', ['-C', platformRoot, 'rev-parse', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

function main() {
  if (!existsSync(schemaRoot)) {
    throw new Error(
      'No platform checkout at .mmap-platform. Run `pnpm schema:link` (or `pnpm bootstrap`) first.',
    );
  }

  const pin = readJson(join(repoRoot, 'schema-pin.json'));
  const registry = readJson(join(schemaRoot, 'registry.json'));

  const entry = registry.protocols.find((p) => p.assessment_type === pin.protocol);
  if (!entry) {
    throw new Error(
      `Pinned protocol "${pin.protocol}" is not in the platform registry. ` +
        `Available: ${registry.protocols.map((p) => p.assessment_type).join(', ')}.`,
    );
  }

  if (entry.protocol_version !== pin.protocol_version) {
    throw new Error(
      `Protocol version mismatch.\n` +
        `  schema-pin.json expects ${pin.protocol}@${pin.protocol_version}\n` +
        `  linked platform provides ${pin.protocol}@${entry.protocol_version}\n\n` +
        `If this bump is intentional, update schema-pin.json, add a corpus fixture for the new\n` +
        `version under src/contract/fixtures/, and confirm the whole corpus still passes.`,
    );
  }

  const commit = resolvedCommit();
  if (commit && commit !== pin.commit) {
    const message = `Linked platform is at ${commit.slice(0, 12)}, pin records ${pin.commit.slice(0, 12)}.`;
    if (isCi) {
      throw new Error(`${message}\nCI must build against the pinned commit exactly.`);
    }
    console.warn(`warning: ${message} Fine for local work; CI pins exactly.`);
  }

  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    outFile,
    `// GENERATED by scripts/sync-schema-pin.mjs — do not edit.
// Source of truth: schema-pin.json

/** Assessment protocol this build captures against. */
export const PROTOCOL = ${JSON.stringify(pin.protocol)} as const;

/** Protocol version stamped onto every record this build creates. */
export const PROTOCOL_VERSION = ${JSON.stringify(pin.protocol_version)} as const;

/** Platform commit supplying @mmap/schema for this build. */
export const SCHEMA_COMMIT = ${JSON.stringify(pin.commit)} as const;
`,
    'utf8',
  );

  console.log(
    `schema pin OK — ${pin.protocol}@${pin.protocol_version} ` +
      `(${pin.commit.slice(0, 12)}) → src/core/src/generated/pin.ts`,
  );
}

try {
  main();
} catch (error) {
  console.error(`\nsync-schema-pin failed:\n${error.message}\n`);
  process.exit(1);
}

/**
 * Generates src/core/src/generated/brand.ts from the platform's
 * @mmap/brand tokens.css.
 *
 * The manatee app and the platform's field PWA are the same product line, so
 * their palette and type scale come from one source rather than two lists of
 * hex codes that agree today and drift next season. Copying the values here
 * would look identical on the day it was written and be wrong within a year;
 * generating them makes the agreement structural.
 *
 * React Native cannot consume CSS custom properties, so the values are lifted
 * into typed constants. The CSS remains the source of truth — if a token is
 * added or renamed upstream, this picks it up on the next `pnpm brand:sync`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokensCss = join(repoRoot, '.mmap-platform', 'packages', 'brand', 'tokens.css');
const outDir = join(repoRoot, 'src', 'core', 'src', 'generated');
const outFile = join(outDir, 'brand.ts');

/** Tokens the app depends on. Missing any of these is an error, not a warning. */
const REQUIRED = {
  base: ['brand-ink', 'brand-teal', 'brand-teal-strong', 'brand-cyan', 'brand-focus', 'brand-aqua'],
  dark: ['bg', 'surface', 'text', 'text-muted', 'accent', 'border'],
};

/**
 * Extracts custom properties from one CSS block.
 *
 * Deliberately a narrow reader rather than a CSS parser: tokens.css is a flat
 * list of `--name: value;` declarations, and a real parser would be more code
 * to go wrong than the thing it replaces.
 */
function readBlock(css, selector) {
  const start = css.indexOf(selector);
  if (start === -1) {
    throw new Error(`tokens.css has no "${selector}" block`);
  }
  const open = css.indexOf('{', start);
  const close = css.indexOf('}', open);
  if (open === -1 || close === -1) {
    throw new Error(`"${selector}" block in tokens.css is malformed`);
  }

  const declarations = {};
  for (const line of css.slice(open + 1, close).split(';')) {
    const match = line.match(/^\s*--([\w-]+)\s*:\s*(.+?)\s*$/);
    if (match) {
      declarations[match[1]] = match[2];
    }
  }
  return declarations;
}

/** Resolves `var(--x)` indirection so the app gets literal values. */
function flatten(declarations, base) {
  const resolved = {};
  for (const [name, raw] of Object.entries(declarations)) {
    let value = raw;
    for (let depth = 0; depth < 5 && value.startsWith('var('); depth += 1) {
      const ref = value.slice(4, -1).replace(/^--/, '').trim();
      const next = declarations[ref] ?? base[ref];
      if (next === undefined) {
        throw new Error(`Token --${name} references --${ref}, which is not defined`);
      }
      value = next;
    }
    resolved[name] = value;
  }
  return resolved;
}

function assertPresent(scope, tokens, required) {
  const missing = required.filter((name) => !(name in tokens));
  if (missing.length > 0) {
    throw new Error(
      `Brand tokens changed upstream: ${scope} no longer defines ${missing.map((n) => `--${n}`).join(', ')}.\n` +
        `Update scripts/sync-brand-tokens.mjs and src/core/src/theme.ts together.`,
    );
  }
}

function toCamel(name) {
  return name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

/**
 * The field PWA sets `:root { font-size: 18px }`, so one rem is 18px there.
 * Spacing and radii are emitted as numbers on that basis — React Native has no
 * rem, and matching the platform's rhythm means matching its root size, not the
 * browser default of 16.
 */
const REM_PX = 18;

function emitValue(value) {
  const rem = value.match(/^(-?[\d.]+)rem$/);
  if (rem) {
    return String(Math.round(Number(rem[1]) * REM_PX));
  }
  return JSON.stringify(value);
}

function emit(name, tokens) {
  const entries = Object.entries(tokens)
    .map(([key, value]) => `  ${toCamel(key)}: ${emitValue(value)},`)
    .join('\n');
  return `export const ${name} = {\n${entries}\n} as const;\n`;
}

function main() {
  if (!existsSync(tokensCss)) {
    throw new Error(
      'No platform checkout at .mmap-platform. Run `pnpm schema:link` (or `pnpm bootstrap`) first.',
    );
  }

  const css = readFileSync(tokensCss, 'utf8');
  const base = flatten(readBlock(css, ':root'), {});
  // The field PWA sets data-theme="dark"; this app matches it so the two read
  // as one product. See docs/DESIGN.md.
  const dark = flatten(readBlock(css, "html[data-theme='dark']"), base);
  const light = flatten(readBlock(css, "html[data-theme='light']"), base);

  assertPresent(':root', base, REQUIRED.base);
  assertPresent("html[data-theme='dark']", dark, REQUIRED.dark);

  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    outFile,
    `// GENERATED by scripts/sync-brand-tokens.mjs — do not edit.
// Source of truth: @mmap/brand/tokens.css in the pinned platform checkout.

/** Raw brand palette and scales, theme-independent. */
${emit('BRAND', base)}
/** The field theme. The platform's field PWA runs this, and so do we. */
${emit('BRAND_DARK', dark)}
/** The platform's public-web theme, kept for reference and print styles. */
${emit('BRAND_LIGHT', light)}`,
    'utf8',
  );

  console.log(
    `brand tokens OK — ${Object.keys(base).length} base, ${Object.keys(dark).length} dark, ` +
      `${Object.keys(light).length} light → src/core/src/generated/brand.ts`,
  );
}

try {
  main();
} catch (error) {
  console.error(`\nsync-brand-tokens failed:\n${error.message}\n`);
  process.exit(1);
}
